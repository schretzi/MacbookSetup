#!/usr/bin/env bash
# Focuses a dedicated kitty instance for the given session file, launching
# it fresh if it isn't already running.
#
# Plain `open -a kitty --args --session X` does NOT work for this: kitty is
# a singleton app on macOS, and `open -a` on an already-running app just
# refocuses it - it does not forward new --args to the running instance
# (confirmed empirically). `-n`/`--new` forces a genuinely new, independent
# OS-level kitty process instead, which is what "dedicated instance" means
# here: each one keeps running in the background between visits, rather
# than sharing one window's tabs. `open` is used deliberately over
# launching the kitty binary directly - it detaches the new process
# cleanly regardless of the caller's own session/controlling terminal
# (matters when called from kanata's root LaunchDaemon), matching the
# already-proven-reliable `open -a` pattern used for plain app switching
# elsewhere in this config.
#
# "Already running" is detected by scanning `ps` output for the exact launch
# command (kitty_bin + args), then focused through that specific instance's
# OWN remote-control socket (every kitty process gets one under
# /tmp/kitty-<pid>, since listen_on is set globally in kitty.conf) - not
# AppleScript/System Events.
#
# `ps`, not `pgrep -f`: confirmed empirically that `pgrep -f` silently fails
# to match some already-running kitty processes on this machine (present and
# correct in `ps` output, invisible to `pgrep -f`/`pgrep -l` no matter how
# permissive the pattern) - cause unconfirmed, but `ps` was reliable in every
# case tested, so detection is built on that instead.
#
# When this script runs as root (invoked from kanata's root LaunchDaemon via
# `cmd`), the focus-window IPC call is run as `schretzi` via `sudo -u`
# instead: confirmed empirically that kitty's remote-control socket accepts
# the connection but then sends EOF (no response) when the connecting peer's
# UID doesn't match the UID that owns the kitty process - `allow_remote_control
# yes` does not override this. Root running `sudo -u` needs no password (root
# already has full authority to become any user). Only used when we're
# actually root, though: this script also runs as plain `schretzi` when
# triggered from kitty.conf's own shortcuts, and `sudo -u schretzi` as
# `schretzi` is a DIFFERENT (non-root-authorized) case that could sit
# waiting on a password prompt that never comes.
set -euo pipefail

session_file="$1"
kitty_bin="/Applications/kitty.app/Contents/MacOS/kitty"

# Hardcoded rather than $HOME: this is also invoked by kanata's root
# LaunchDaemon via `cmd`, which does not set HOME for its children (with
# `set -u` above, an unset $HOME here would abort the script outright -
# "line 49: HOME: unbound variable", and every "^" shortcut silently stops
# working). A ${HOME:-fallback} would dodge the abort but not the real
# problem: when launchd DOES set HOME for a root job it is /var/root, which
# would send every path below to the wrong user's home. So: hardcoded.
home="/Users/schretzi"

# kitty.conf's `startup_session` applies home.kitty-session automatically to
# any bare launch (Dock icon, plain `open -a kitty`, macOS session restore) -
# that process's command line carries no `--session` arg at all, since the
# session came from the config file, not a CLI flag. So a bare kitty process
# also counts as "home is already running"; without this, this script can
# never find the home instance and spawns a duplicate every time.
bare_counts_as_match=0
if [[ "$session_file" == "$home/.config/kitty/sessions/home.kitty-session" ]]; then
  bare_counts_as_match=1
fi

# Dedicated (non-home) instances close themselves - window and OS-level
# process both - the moment the launched program (nvim) exits, instead of
# leaving an empty windowless kitty process running in the background.
# `home` is excluded on purpose: it's the main session you actually live in
# across multiple tabs/windows, and should behave like a normal persistent
# app. These are passed via -o (per-launch override) rather than in
# kitty.conf, since kitty.conf applies to every instance including home.
kitty_args=(--session "$session_file")
if [[ "$bare_counts_as_match" == "0" ]]; then
  kitty_args+=(-o close_on_child_death=yes -o macos_quit_when_last_window_closed=yes)
fi

# Launch through this session's own app wrapper when one exists, so macOS's
# Cmd-Tab shows "Mail"/"Obsidian"/... instead of five identical "kitty"
# entries - the switcher takes its name from the bundle's CFBundleName, and
# every instance sharing /Applications/kitty.app means they all read "kitty".
# The bundles are generated by make-session-apps.sh from session-apps.conf;
# see those for how and why. Sessions with no entry (home) fall through to
# plain kitty.app exactly as before, as does any session whose bundle hasn't
# been generated yet - so this stays functional on a machine where
# make-session-apps.sh has never been run.
#
# A private overlay repo declares its own sessions in
# ~/.config/kitty/session-apps.d/*.conf, mirroring the `globinclude
# local.d/*.conf` that kitty.conf itself uses - the base session-apps.conf
# must not name overlay-only sessions, or a machine without the overlay
# builds a wrapper for a session it does not have. Overlay files are read
# first, so an overlay can also override a base glob.
conf="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/../session-apps.conf"
session_name="$(basename "$session_file" .kitty-session)"
app_name=""
shopt -s nullglob
session_app_confs=("$home/.config/kitty/session-apps.d/"*.conf "$conf")
shopt -u nullglob
for session_app_conf in ${session_app_confs[@]+"${session_app_confs[@]}"}; do
  [[ -r "$session_app_conf" ]] || continue
  while IFS='|' read -r glob name _letter _rgb; do
    [[ -z "${glob// }" || "${glob:0:1}" == "#" ]] && continue
    # $glob unquoted on purpose: these are globs, and matching them is the
    # whole point (daily-note-* has to cover daily-note-YYYY-MM-DD).
    # shellcheck disable=SC2254
    case "$session_name" in
      $glob) app_name="$name"; break ;;
    esac
  done < "$session_app_conf"
  [[ -n "$app_name" ]] && break
done

app_bundle=""
launch_bin="$kitty_bin"
if [[ -n "$app_name" ]] && [[ -d "$home/Applications/Kitty Sessions/$app_name.app" ]]; then
  app_bundle="$home/Applications/Kitty Sessions/$app_name.app"
  # The wrapper's own copy of the kitty launcher - this, not kitty_bin, is
  # what shows up in `ps` for a wrapped instance, so it's what find_pid has
  # to match on. kitty_bin stays the real binary and is still used for the
  # remote-control call below, which is just a client and works either way.
  launch_bin="$app_bundle/Contents/MacOS/$app_name"
fi

find_pid() {
  local candidate_pid cmd expected_cmd
  expected_cmd="$launch_bin"
  for a in "${kitty_args[@]}"; do
    expected_cmd="$expected_cmd $a"
  done
  # `read -r pid cmd` with the DEFAULT IFS, deliberately - not
  # `IFS= read -r line` plus ${line%% *}/${line#* }. ps right-pads the pid
  # column to five characters, so a four-digit pid arrives as " 2349 /path".
  # Splitting that by hand on the first space yields an EMPTY pid and a cmd
  # of "2349 /path..." which then matches nothing, so the script concludes
  # the instance isn't running and launches a duplicate. Default-IFS `read`
  # skips the leading blanks and does the right thing at any pid width.
  # This bites only while pids are short, i.e. after the pid counter wraps -
  # which is exactly when it showed up, long after the code was written.
  while read -r candidate_pid cmd; do
    if [[ "$cmd" == "$expected_cmd" ]] \
      || { [[ "$bare_counts_as_match" == "1" ]] && [[ "$cmd" == "$launch_bin" ]]; }; then
      printf '%s\n' "$candidate_pid"
      return 0
    fi
  done < <(ps -axo pid=,command=)
  return 1
}

# Serialize concurrent invocations for the same session file. Without this,
# two near-simultaneous calls (e.g. a key repeating while the trigger is held
# a beat too long) can both run the "already running?" check before the
# first one's kitty process has even shown up in `ps`, and both decide to
# launch - producing two instances of the same dedicated session. `mkdir` is
# atomic on a local filesystem, so it doubles as a portable lock (no `flock`
# binary on stock macOS).
lock_dir="/tmp/kitty-focus-or-launch.lock.$(basename "$session_file")"
lock_acquired=0
lock_deadline=$((SECONDS + 5))
while (( SECONDS < lock_deadline )); do
  if mkdir "$lock_dir" 2>/dev/null; then
    lock_acquired=1
    break
  fi
  sleep 0.1
done
if [[ "$lock_acquired" == "1" ]]; then
  trap 'rmdir "$lock_dir" 2>/dev/null || true' EXIT
fi

pid="$(find_pid || true)"

if [[ -n "$pid" ]] && [[ -S "/tmp/kitty-$pid" ]]; then
  if [[ "$(id -u)" == "0" ]]; then
    sudo -u schretzi "$kitty_bin" @ --to "unix:/tmp/kitty-$pid" focus-window >/dev/null 2>&1 && exit 0
  else
    "$kitty_bin" @ --to "unix:/tmp/kitty-$pid" focus-window >/dev/null 2>&1 && exit 0
  fi
fi

if [[ -n "$app_bundle" ]]; then
  open -a "$app_bundle" -n --args "${kitty_args[@]}"
else
  open -a kitty -n --args "${kitty_args[@]}"
fi

# Hold the lock until the new instance's socket actually exists (or we give
# up after 5s), so an invocation queued behind this one sees it as already
# running instead of racing to launch a second copy.
wait_deadline=$((SECONDS + 5))
while (( SECONDS < wait_deadline )); do
  new_pid="$(find_pid || true)"
  if [[ -n "$new_pid" ]] && [[ -S "/tmp/kitty-$new_pid" ]]; then
    break
  fi
  sleep 0.1
done
