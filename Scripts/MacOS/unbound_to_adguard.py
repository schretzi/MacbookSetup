#!/usr/bin/env python3
"""Translate the live unbound configuration into AdGuard Home's equivalents.

unbound is the resolver this machine runs today (see Setup.md -> DNS). This
script exists so AdGuard Home can be tried out *next to* it without the two
drifting apart: unbound's conf.d stays the single source of truth for zones and
upstreams, and everything AdGuard Home needs is regenerated from it.

Two things come out of one pass over conf.d:

  upstreams.conf    AdGuard Home's `dns.upstream_dns_file`. Every forward-zone
                    becomes either a plain upstream line (the "." zone) or a
                    domain-specific `[/zone/]addr` line.

  zones/<name>.txt  One AdGuard Home filtering-rule list per unbound conf file,
                    mirroring the conf.d profile model: kiac.conf ->
                    zones/kiac.txt. local-zone/local-data become $dnsrewrite
                    rules.

Zone types translate as follows, matching the cheat sheet in Setup.md:

  transparent   answer what is listed, forward the rest
                -> one rewrite rule per local-data, nothing else
  static        answer what is listed, NXDOMAIN for the rest
                -> a `||zone^$dnsrewrite=NXDOMAIN` catch-all, plus an
                   `@@`-exception for every name that *is* listed, so the
                   catch-all does not swallow it
  redirect      every name under the zone answers with the zone's own data
                -> the catch-all itself carries the address

The `@@`-exception is load-bearing. AdGuard Home returns the first non-NOERROR
rewrite it finds among the matching rules, so without the exception the
NXDOMAIN catch-all would win over the specific A record for every defined name.

What deliberately does not carry over:

  domain-insecure   AdGuard Home does not validate DNSSEC itself - `enable_dnssec`
                    only sets the DO/AD bits towards the upstream and trusts its
                    answer. There is therefore no local validation to exempt a
                    split-horizon zone from. These lines are counted and
                    reported, not translated.

Usage:
    unbound_to_adguard.py                      # write into /etc/adguardhome
    unbound_to_adguard.py --dry-run            # print what would be written
    unbound_to_adguard.py --out-dir /tmp/agh   # somewhere else
"""

from __future__ import annotations

import argparse
import os
import re
import shlex
import sys
from dataclasses import dataclass, field
from pathlib import Path

DEFAULT_CONF_D = Path("/opt/homebrew/etc/unbound/conf.d")

# Written into the head of every generated zone file, and the only thing that
# makes a file in zones/ safe to prune - see the stale-file loop in main().
GENERATED_MARKER = "Generated by Scripts/MacOS/unbound_to_adguard.py"
DEFAULT_OUT_DIR = Path("/etc/adguardhome")

# unbound block headers. A line consisting of one of these opens a section;
# every `key: value` after it belongs to that section until the next header.
# Indentation is irrelevant to unbound, so it is irrelevant here too - the work
# overlay's corp.conf indents forward-addr under name and unbound reads it fine.
BLOCK_HEADERS = {
    "server",
    "forward-zone",
    "stub-zone",
    "auth-zone",
    "view",
    "remote-control",
    "python",
    "dynlib",
    "rpz",
    "cachedb",
    "dnscrypt",
    "ipset",
    "tls",
}

# Record types worth translating. AdGuard Home's $dnsrewrite understands more,
# but these are the ones the unbound zone files here actually use.
SUPPORTED_RR = {"A", "AAAA", "CNAME", "TXT", "MX", "SRV", "PTR"}


@dataclass
class ForwardZone:
    """One unbound forward-zone or stub-zone."""

    name: str
    addrs: list[str] = field(default_factory=list)
    source: str = ""


@dataclass
class LocalZone:
    """One unbound local-zone plus the local-data that belongs to it."""

    name: str
    zone_type: str
    source: str = ""


@dataclass
class LocalData:
    """One unbound local-data record."""

    owner: str
    rr_type: str
    value: str
    source: str = ""


@dataclass
class UnboundConfig:
    """Everything one pass over conf.d found."""

    forwards: list[ForwardZone] = field(default_factory=list)
    zones: list[LocalZone] = field(default_factory=list)
    data: list[LocalData] = field(default_factory=list)
    insecure: list[str] = field(default_factory=list)
    skipped: list[str] = field(default_factory=list)


def strip_comment(line: str) -> str:
    """Remove an unbound comment, honouring quotes.

    `local-data: "foo A 1.2.3.4"  # note` has to keep the quoted part intact,
    so a naive split on '#' is wrong for any value that contains one.
    """
    out = []
    in_quotes = False
    for ch in line:
        if ch == '"':
            in_quotes = not in_quotes
        if ch == "#" and not in_quotes:
            break
        out.append(ch)
    return "".join(out)


def unquote(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def parse_conf(path: Path, cfg: UnboundConfig) -> None:
    """Parse one unbound .conf into cfg."""
    source = path.name
    block = ""
    # The forward-zone currently being filled: unbound allows name and
    # forward-addr in any order, so the zone is appended when it is complete
    # rather than when its name is seen.
    pending: ForwardZone | None = None
    # The local-zone most recently declared, only used to attribute a source.
    for raw in path.read_text(errors="replace").splitlines():
        line = strip_comment(raw).strip()
        if not line:
            continue

        head = line.rstrip(":").strip()
        if line.endswith(":") and head in BLOCK_HEADERS:
            if pending is not None:
                cfg.forwards.append(pending)
                pending = None
            block = head
            if block in ("forward-zone", "stub-zone"):
                pending = ForwardZone(name="", source=source)
            continue

        if ":" not in line:
            continue
        key, _, value = line.partition(":")
        key = key.strip()
        value = value.strip()

        if block in ("forward-zone", "stub-zone"):
            if pending is None:
                pending = ForwardZone(name="", source=source)
            if key == "name":
                pending.name = unquote(value)
            elif key in ("forward-addr", "stub-addr", "forward-host", "stub-host"):
                pending.addrs.append(unquote(value))
            continue

        if block != "server":
            continue

        if key == "local-zone":
            parts = shlex.split(value)
            if len(parts) >= 2:
                cfg.zones.append(
                    LocalZone(
                        name=parts[0].rstrip("."),
                        zone_type=parts[1].lower(),
                        source=source,
                    )
                )
            continue

        if key == "local-data":
            parts = unquote(value).split()
            # "name [TTL] [CLASS] TYPE rdata..." - unbound allows an optional
            # TTL and class, so find the record type rather than assuming
            # position 1.
            idx = next(
                (
                    i
                    for i, p in enumerate(parts)
                    if p.upper() in SUPPORTED_RR and i > 0
                ),
                -1,
            )
            if idx < 0 or idx + 1 >= len(parts):
                cfg.skipped.append(f"{source}: local-data: {value}")
                continue
            cfg.data.append(
                LocalData(
                    owner=parts[0].rstrip("."),
                    rr_type=parts[idx].upper(),
                    value=" ".join(parts[idx + 1 :]),
                    source=source,
                )
            )
            continue

        if key == "domain-insecure":
            cfg.insecure.append(unquote(value))
            continue

    if pending is not None:
        cfg.forwards.append(pending)


def read_conf_d(conf_d: Path) -> UnboundConfig:
    cfg = UnboundConfig()
    if not conf_d.is_dir():
        sys.exit(f"error: {conf_d} is not a directory")
    # Sorted so the output is stable between runs and diffable.
    for path in sorted(conf_d.glob("*.conf")):
        # conf.d is mostly symlinks into this repository and the overlays;
        # a dangling one is exactly what the unbound role prunes, so skip it
        # here rather than crashing.
        if not path.exists():
            cfg.skipped.append(f"{path.name}: dangling symlink")
            continue
        parse_conf(path, cfg)
    return cfg


def render_upstreams(cfg: UnboundConfig) -> str:
    """Render AdGuard Home's upstream_dns_file.

    The "." zone becomes plain upstream lines; every other forward-zone becomes
    a domain-specific `[/zone/]addr` line, which is AdGuard Home's equivalent of
    a forward-zone.
    """
    default: list[tuple[str, str]] = []
    specific: list[tuple[str, str, str]] = []
    for fz in cfg.forwards:
        name = fz.name.rstrip(".")
        for addr in fz.addrs:
            if name in ("", "."):
                default.append((addr, fz.source))
            else:
                specific.append((name, addr, fz.source))

    # AdGuard Home only treats a line as a comment when it *starts* with '#'
    # (aghnet.IsCommentOrEmpty). A trailing "1.2.3.4  # note" is split on
    # whitespace and the '#' is parsed as a second upstream address, which the
    # daemon rejects one line at a time. So provenance goes on its own line.
    out = [
        "# Generated by Scripts/MacOS/unbound_to_adguard.py - do not edit.",
        "# Source: unbound's conf.d. Regenerate instead of editing here.",
        "#",
        "# Comments must be on their own line here - AdGuard Home does not",
        "# strip a trailing '#' comment from an upstream line.",
        "",
    ]
    if default:
        out.append('# --- default upstreams (unbound forward-zone ".") ---')
        seen_default = set()
        for addr, source in default:
            if addr in seen_default:
                continue
            seen_default.add(addr)
            out.append(f"# from {source}")
            out.append(addr)
        out.append("")
    if specific:
        out.append("# --- per-domain upstreams (unbound forward-zone <name>) ---")
        seen_specific = set()
        last_source = None
        for name, addr, source in specific:
            key = (name, addr)
            if key in seen_specific:
                continue
            seen_specific.add(key)
            if source != last_source:
                out.append(f"# from {source}")
                last_source = source
            out.append(f"[/{name}/]{addr}")
        out.append("")
    if not default and not specific:
        out.append("# No forward-zone found in conf.d.")
        out.append("")
    return "\n".join(out)


def rewrite_value(rr_type: str, value: str) -> str | None:
    """Render the $dnsrewrite payload for one record, or None if unsupported."""
    if rr_type in ("A", "AAAA"):
        return f"NOERROR;{rr_type};{value}"
    if rr_type == "CNAME":
        return f"NOERROR;CNAME;{value.rstrip('.')}"
    if rr_type in ("TXT", "MX", "SRV", "PTR"):
        return f"NOERROR;{rr_type};{value}"
    return None


def render_zone_file(source: str, cfg: UnboundConfig) -> str | None:
    """Render one AdGuard Home rule list from the local zones of one conf file."""
    zones = [z for z in cfg.zones if z.source == source]
    data = [d for d in cfg.data if d.source == source]
    if not zones and not data:
        return None

    out = [
        f"! {GENERATED_MARKER} from {source}",
        "! Do not edit - regenerate instead. Source of truth is unbound's conf.d.",
        "",
    ]

    owners = {d.owner for d in data}

    for zone in zones:
        zone_name = zone.name
        zone_data = [d for d in data if d.owner == zone_name]
        out.append(f"! local-zone: {zone_name} {zone.zone_type}")

        if zone.zone_type == "static":
            # Everything under the zone is ours: answer what is listed, and
            # NXDOMAIN the rest instead of leaking it upstream.
            out.append(f"||{zone_name}^$dnsrewrite=NXDOMAIN")
            # AdGuard Home returns the first non-NOERROR rewrite among the
            # matching rules, so every name that IS defined has to cancel the
            # catch-all explicitly or it would come back NXDOMAIN too. That
            # covers both local-data owners and any zone nested below this one
            # (kiac.conf redirects apps.main.kiac inside the static kiac zone).
            nested = {
                z.name
                for z in zones
                if z.name != zone_name
                and z.zone_type != "static"
                and is_under(z.name, zone_name)
            }
            defined = {o for o in owners if is_under(o, zone_name)} | nested
            for owner in sorted(defined):
                out.append(f"@@||{owner}^$dnsrewrite=NXDOMAIN")
        elif zone.zone_type == "redirect":
            # Every name under the zone answers with the zone's own data.
            for d in zone_data:
                payload = rewrite_value(d.rr_type, d.value)
                if payload:
                    out.append(f"||{zone_name}^$dnsrewrite={payload}")
        elif zone.zone_type in ("refuse", "always_refuse"):
            out.append(f"||{zone_name}^$dnsrewrite=REFUSED")
        elif zone.zone_type in ("transparent", "typetransparent", "nodefault"):
            # Listed names are answered below; everything else forwards. That
            # is AdGuard Home's default behaviour, so nothing to emit.
            pass
        else:
            out.append(f"! unsupported zone type {zone.zone_type!r} - not translated")
        out.append("")

    if data:
        out.append("! local-data")
        for d in sorted(data, key=lambda d: (d.owner, d.rr_type)):
            payload = rewrite_value(d.rr_type, d.value)
            if payload is None:
                out.append(f"! unsupported record: {d.owner} {d.rr_type} {d.value}")
                continue
            out.append(f"||{d.owner}^$dnsrewrite={payload}")
        out.append("")

    # A name can be both a redirect zone apex and a local-data owner, which
    # produces the same rule twice. Collapse those, keeping first-seen order so
    # the file stays readable and diffable.
    deduped = []
    seen = set()
    for line in out:
        if line.startswith(("||", "@@")) and line in seen:
            continue
        seen.add(line)
        deduped.append(line)

    return "\n".join(deduped)


def is_under(name: str, zone: str) -> bool:
    """Is name inside zone (or the zone apex itself)?"""
    return name == zone or name.endswith("." + zone)


def main() -> int:
    ap = argparse.ArgumentParser(
        description="Translate unbound's conf.d into AdGuard Home configuration.",
    )
    ap.add_argument(
        "--conf-d",
        type=Path,
        default=DEFAULT_CONF_D,
        help=f"unbound conf.d directory (default: {DEFAULT_CONF_D})",
    )
    ap.add_argument(
        "--out-dir",
        type=Path,
        default=DEFAULT_OUT_DIR,
        help=f"AdGuard Home directory to write into (default: {DEFAULT_OUT_DIR})",
    )
    ap.add_argument(
        "--dry-run",
        action="store_true",
        help="print what would be written instead of writing it",
    )
    args = ap.parse_args()

    cfg = read_conf_d(args.conf_d)

    upstreams = render_upstreams(cfg)
    sources = sorted({z.source for z in cfg.zones} | {d.source for d in cfg.data})
    zone_files = {}
    for source in sources:
        rendered = render_zone_file(source, cfg)
        if rendered:
            zone_files[Path(source).stem + ".txt"] = rendered

    if args.dry_run:
        print(f"=== {args.out_dir}/upstreams.conf ===")
        print(upstreams)
        for name, body in zone_files.items():
            print(f"=== {args.out_dir}/zones/{name} ===")
            print(body)
    else:
        zones_dir = args.out_dir / "zones"
        zones_dir.mkdir(parents=True, exist_ok=True)
        write_if_changed(args.out_dir / "upstreams.conf", upstreams)
        for name, body in zone_files.items():
            write_if_changed(zones_dir / name, body)
        # A zone file whose unbound source disappeared would otherwise keep
        # being loaded by AdGuard Home for ever.
        #
        # Only files this script wrote are candidates. Zones are being migrated
        # off unbound to native AdGuard Home rule lists installed by the
        # `adguardhome` Ansible role, one zone at a time, so during the
        # migration both kinds share this directory. Pruning by name alone
        # would delete every already-migrated zone on the next run - which is
        # exactly the silent DNS outage this whole area keeps producing.
        for stale in zones_dir.glob("*.txt"):
            if stale.name in zone_files:
                continue
            try:
                head = stale.read_text().lstrip().split("\n", 1)[0]
            except OSError:
                continue
            if GENERATED_MARKER not in head:
                continue
            print(f"removing stale {stale}", file=sys.stderr)
            stale.unlink()

    # Report what was seen, and in particular what was not translated: a silent
    # partial translation is the failure mode worth avoiding here.
    print(
        f"forward-zones: {len(cfg.forwards)}  "
        f"local-zones: {len(cfg.zones)}  "
        f"local-data: {len(cfg.data)}",
        file=sys.stderr,
    )
    if cfg.insecure:
        print(
            f"domain-insecure: {len(cfg.insecure)} entries not translated - AdGuard "
            "Home does not validate DNSSEC locally, so there is nothing to exempt.",
            file=sys.stderr,
        )
    for skipped in cfg.skipped:
        print(f"skipped: {skipped}", file=sys.stderr)

    return 0


def write_if_changed(path: Path, body: str) -> None:
    if path.exists() and path.read_text() == body:
        return
    path.write_text(body)
    os.chmod(path, 0o644)
    print(f"wrote {path}", file=sys.stderr)


if __name__ == "__main__":
    sys.exit(main())
